import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Script} from 'node:vm';
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
for(const [,code] of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g))new Script(code);
assert.doesNotMatch(html,/activityNoteTitle|<label[^>]*>Title<\/label><input id="activityNoteTitle"/);
assert.match(html,/<label for="activityNoteDetails">Note \/ paste email text<\/label>/);
assert.match(html,/<textarea id="activityNoteDetails" class="activity-note-text"/);
assert.match(html,/\.activity-note-form textarea\{display:block;width:100%;min-height:120px;background:#141f32;color:#edf3ff;border:1px solid #384760;border-radius:10px/);
assert.match(html,/:root\[data-theme="light"\] \.activity-note-form textarea\{background:#fff;color:#1c2b42;border-color:#c9d4e5\}/);
assert.match(html,/const details=\$\('activityNoteDetails'\)\.value\.trim\(\)/);
assert.match(html,/if\(!details&&!practiceTime&&!location\)throw Error\('Enter a note, time or location\.'\)/);
assert.match(html,/const title='Note';/);
assert.match(html,/const record=\{household_id:HOUSE,activity_id:a\.id,created_by:user\.id,title,details,/);
assert.match(html,/date:n\.session_date\|\|'',title:n\.title==='Note'\?/);
assert.match(html,/a\.title==='Note'\?'':'<strong>'\+esc\(a\.title\)/);
assert.match(html,/activityUpdates\.unshift\(saved\)/);
assert.match(html,/showActivityNoteList\(\);render\(\)/);
assert.match(html,/<h3>Add a note<\/h3>/);
console.log('PASS: titleless activity notes retain required schema field, render useful preview, and use consistent textarea in light and dark themes.');
